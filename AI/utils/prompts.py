_overrides: dict[str, str] = {}


def set_overrides(overrides: dict[str, str] | None) -> None:
    """整表替换进程内覆盖注册表（每次 propagate/rerun 前由平台快照调用）。

    传 None/空 dict 清空注册表；CLI 与内核测试不调用 → 恒默认。
    """
    global _overrides
    _overrides = dict(overrides or {})


def get_override(node_id: str | None) -> str | None:
    """返回 node_id 的覆盖文本；无覆盖/覆盖为空串 → None。"""
    if not node_id:
        return None
    text = _overrides.get(node_id)
    return text if text else None


def get_system_prompt(
    node_id: str | None,
    default: str | Callable[[], str],
) -> str:
    """覆盖存在且非空 → 原样返回覆盖文本；否则返回 default。

    default 为 callable 时惰性求值（覆盖场景避免白跑数据/模板组装）。
    """
    override = get_override(node_id)
    if override is not None:
        return override
    return default() if callable(default) else default


def system_message(
    node_id: str | None,
    default: Callable[[], str],
):
    """ChatPromptTemplate.from_messages 的 system 条目（A 类分析师专用）。

    覆盖命中 → 静态 SystemMessage（花括号**原样**进入 LLM——元组形式会被
    langchain 当模板解析，覆盖含 {xxx}/JSON 示例即 KeyError，实测 1.5.3）；
    否则 → ("system", 模板文本) 元组（数据占位符由工厂 partial 填充）。
    """
    from langchain_core.messages import SystemMessage

    override = get_override(node_id)
    if override is not None:
        return SystemMessage(content=override)
    return ("system", default())
