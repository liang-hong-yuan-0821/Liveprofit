@lru_cache(maxsize=None)
def output_format_for(node_id: str) -> str:
    """node_id 的输出格式模板内容（backend 展示默认提示词时展开 {output_format} 锚点）。"""
    key = _FORMAT_MAP.get(node_id)
    if key is None:
        return ""
    from AI.templates import load_output_format

    return load_output_format(*key)


def render_default_prompt(node_id: str) -> str:
    """展示用默认提示词：{date_line} 移除（运行时日期行）、{output_format} 展开。"""
    text = DEFAULT_PROMPTS.get(node_id, "")
    text = text.replace("{date_line}", "")
    if "{output_format}" in text:
        text = text.replace("{output_format}", output_format_for(node_id))
    return text


